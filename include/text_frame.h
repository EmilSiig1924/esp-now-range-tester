// 128x32 monochrome frame in SSD1306 page order: four 8-pixel-high pages,
// one byte per column. Each text line occupies one page; 21 six-pixel cells
// fit across. Text beyond the edge is clipped, and unknown characters show '?'.
struct TextFrame {
    static constexpr int width = 128;
    static constexpr int lines = 4;
    static constexpr int columns = width / 6;
    uint8_t pixels[lines * width] = {};

    constexpr void clear() {
        for (auto& column : pixels) column = 0;
    }

    constexpr void drawText(int line, const char* text) {
        if (line < 0 || line >= lines || !text) return;
        for (int cell = 0; cell < columns && text[cell]; ++cell) {
            const unsigned char ch = static_cast<unsigned char>(text[cell]);
            const auto& glyph = font5x7[(ch >= 0x20 && ch <= 0x7E ? ch : '?') - 0x20];
            uint8_t* column = &pixels[line * width + cell * 6];
            for (int x = 0; x < 5; ++x) column[x] = glyph[x];
            column[5] = 0;
        }
    }
};

// Text for one screen update; formatted by the caller, rendered by the display task.
struct ScreenText {
    char line[TextFrame::lines][TextFrame::columns + 1] = {};
};
